let _geoSeq = 0;

function _geoPath(polys, px, py) {
  let d = '';
  for (const poly of polys) {
    for (let i = 0; i < poly.length; i++) {
      d += (i ? 'L' : 'M') + px(poly[i][0]).toFixed(1) + ' ' + py(poly[i][1]).toFixed(1);
    }
    d += 'Z';
  }
  return d;
}

function _geoFmtRange(a, b, pos, neg) {
  const f = v => Math.abs(v).toFixed(1).replace(/\.0$/, '') + '°' + (v < 0 ? neg : pos);
  return f(a) + '–' + f(b);
}

function _geoEsc(s) {
  return String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}

// bounds = { lon: [west, east], lat: [south, north] }; opts = { width = 320, label = '' }
function geoLocatorSVG(bounds, opts = {}) {
  const W = Math.round(opts.width || 320);
  const label = opts.label || '';
  const id = 'geo' + (++_geoSeq);
  const H = Math.round(W * 0.88);      // map area height
  const CAP = 22;                      // caption strip
  const EX = GEO_EXTENT;
  const bw = bounds.lon[1] - bounds.lon[0], bh = bounds.lat[1] - bounds.lat[0];
  const cLon = (bounds.lon[0] + bounds.lon[1]) / 2, cLat = (bounds.lat[0] + bounds.lat[1]) / 2;

  // --- auto-zoom: bounds ×4 around the centre, min 12° lon, clamped to the extent ---
  const k = Math.cos(Math.max(5, Math.min(45, cLat)) * Math.PI / 180); // lon squeeze at this latitude
  const latPerLon = k * H / W;         // degrees of lat shown per degree of lon shown
  let lonSpan = Math.max(12, bw * 4, (bh * 4) / latPerLon);
  lonSpan = Math.min(lonSpan, EX.lon[1] - EX.lon[0], (EX.lat[1] - EX.lat[0]) / latPerLon);
  const latSpan = lonSpan * latPerLon;
  const west = Math.max(EX.lon[0], Math.min(EX.lon[1] - lonSpan, cLon - lonSpan / 2));
  const south = Math.max(EX.lat[0], Math.min(EX.lat[1] - latSpan, cLat - latSpan / 2));
  const north = south + latSpan;
  const px = lon => (lon - west) / lonSpan * W;
  const py = lat => (north - lat) / latSpan * H;

  const FONT = 'font-family="system-ui,-apple-system,\'Segoe UI\',\'Noto Sans TC\',sans-serif"';
  let s = `<svg xmlns="http://www.w3.org/2000/svg" id="${id}" class="geo-locator" width="${W}" height="${H + CAP}" ` +
    `viewBox="0 0 ${W} ${H + CAP}" role="img" aria-label="${_geoEsc(label || 'map locator')}">`;
  s += `<defs><clipPath id="${id}-clip"><rect x="0" y="0" width="${W}" height="${H}"/></clipPath>`;

  // --- inset geometry (decide corner so it never covers the mission box) ---
  const iw = Math.round(W * 0.28), ih = Math.round(iw * 145 / 360), pad = 4;
  const bx0 = px(bounds.lon[0]), bx1 = px(bounds.lon[1]), by0 = py(bounds.lat[1]), by1 = py(bounds.lat[0]);
  let ix = W - iw - pad;
  const iy = H - ih - pad;
  if (bx1 > ix - 12 && by1 > iy - 12) ix = pad;
  s += `<clipPath id="${id}-iclip"><rect x="${ix}" y="${iy}" width="${iw}" height="${ih}"/></clipPath></defs>`;

  // --- sea, land ---
  s += `<rect x="0" y="0" width="${W}" height="${H + CAP}" fill="#0f141a"/>`;
  s += `<rect x="0" y="0" width="${W}" height="${H}" fill="#121c26"/>`;
  s += `<g clip-path="url(#${id}-clip)">`;
  s += `<path d="${_geoPath(GEO_OUTLINES, px, py)}" fill="#2c3a2c" stroke="#5d6b5d" stroke-width="0.8" stroke-linejoin="round"/>`;

  // --- graticule ---
  const step = lonSpan <= 25 ? 5 : 10;
  let grid = '', labels = '';
  for (let lon = Math.ceil(west / step) * step; lon <= west + lonSpan; lon += step) {
    const x = px(lon);
    grid += `M${x.toFixed(1)} 0V${H}`;
    if (x > 14 && x < W - 14) labels += `<text x="${(x + 2).toFixed(1)}" y="9">${lon}°E</text>`;
  }
  for (let lat = Math.ceil(south / step) * step; lat <= north; lat += step) {
    const y = py(lat);
    grid += `M0 ${y.toFixed(1)}H${W}`;
    if (y > 16 && y < H - 6) labels += `<text x="2" y="${(y - 2).toFixed(1)}">${lat}°N</text>`;
  }
  s += `<path d="${grid}" fill="none" stroke="#dfe6ee" stroke-opacity="0.13" stroke-width="0.5"/>`;
  s += `<g ${FONT} font-size="8" fill="#dfe6ee" fill-opacity="0.55">${labels}</g>`;

  // --- mission box ---
  const rw = Math.max(1.5, bx1 - bx0), rh = Math.max(1.5, by1 - by0);
  const mx = (bx0 + bx1) / 2, my = (by0 + by1) / 2;
  s += `<rect x="${(mx - rw / 2).toFixed(1)}" y="${(my - rh / 2).toFixed(1)}" width="${rw.toFixed(1)}" height="${rh.toFixed(1)}" ` +
    `fill="#e0b54a" fill-opacity="0.22" stroke="#e0b54a" stroke-width="1.5"/>`;
  let top = my - rh / 2;
  if (rw < 10 || rh < 10) {
    const r = Math.max(rw, rh) / 2 + 7;
    s += `<circle cx="${mx.toFixed(1)}" cy="${my.toFixed(1)}" r="${r.toFixed(1)}" fill="none" stroke="#e0b54a" stroke-width="1.2"/>`;
    s += `<path d="M${(mx - r - 5).toFixed(1)} ${my.toFixed(1)}h5M${(mx + r).toFixed(1)} ${my.toFixed(1)}h5` +
      `M${mx.toFixed(1)} ${(my - r - 5).toFixed(1)}v5M${mx.toFixed(1)} ${(my + r).toFixed(1)}v5" stroke="#e0b54a" stroke-width="1.2"/>`;
    top = my - r - 5;
  }
  if (label) {
    const above = top > 20;
    const ly = above ? top - 5 : my + (my - top) + 14;
    const lx = Math.max(6, Math.min(W - 6, mx));
    const anchor = lx < 50 ? 'start' : lx > W - 50 ? 'end' : 'middle';
    s += `<text x="${lx.toFixed(1)}" y="${ly.toFixed(1)}" text-anchor="${anchor}" ${FONT} font-size="13" font-weight="700" ` +
      `fill="#ffe9a8" stroke="#0f141a" stroke-width="3" paint-order="stroke" stroke-linejoin="round">${_geoEsc(label)}</text>`;
  }
  s += '</g>';

  // --- world inset ---
  const wx = lon => ix + (lon + 180) / 360 * iw;
  const wy = lat => iy + (85 - lat) / 145 * ih;
  s += `<rect x="${ix}" y="${iy}" width="${iw}" height="${ih}" fill="#0f141a" fill-opacity="0.92" stroke="#5d6b5d" stroke-width="0.8"/>`;
  s += `<g clip-path="url(#${id}-iclip)"><path d="${_geoPath(GEO_WORLD, wx, wy)}" fill="#3a4a3a" stroke="none"/>`;
  const ex0 = wx(west), ey0 = wy(north);
  const ew = Math.max(4, wx(west + lonSpan) - ex0), eh = Math.max(4, wy(south) - ey0);
  s += `<rect x="${(ex0 + (wx(west + lonSpan) - ex0 - ew) / 2).toFixed(1)}" y="${(ey0 + (wy(south) - ey0 - eh) / 2).toFixed(1)}" ` +
    `width="${ew.toFixed(1)}" height="${eh.toFixed(1)}" fill="#e0b54a" fill-opacity="0.3" stroke="#e0b54a" stroke-width="1"/></g>`;

  // --- frame + caption ---
  s += `<rect x="0.5" y="0.5" width="${W - 1}" height="${H - 1}" fill="none" stroke="#5d6b5d" stroke-width="1"/>`;
  const cap = _geoFmtRange(bounds.lat[0], bounds.lat[1], 'N', 'S') + ', ' + _geoFmtRange(bounds.lon[0], bounds.lon[1], 'E', 'W');
  s += `<text x="${W / 2}" y="${H + 15}" text-anchor="middle" ${FONT} font-size="11" fill="#dfe6ee">${cap}</text>`;
  s += '</svg>';
  return s;
}
