function _geoBlob(lon, lat, rx, ry = rx * 0.8) {
  // small island: octagon around a centre
  const out = [];
  for (let i = 0; i < 8; i++) {
    const a = (i / 8) * Math.PI * 2;
    out.push([+(lon + Math.cos(a) * rx).toFixed(2), +(lat + Math.sin(a) * ry).toFixed(2)]);
  }
  return out;
}

